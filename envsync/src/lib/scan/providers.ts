/**
 * All env-var name variants recognized across the provider database,
 * generated by combining each provider's primary keyword with the
 * canonical suffixes for its category (e.g. Stripe + payments suffixes ->
 * STRIPE_SECRET_KEY, STRIPE_WEBHOOK_SECRET, ...). Computed once at module
 * load and used for coverage stats and the docs "supported providers" page
 * — not for classification itself (see `findProvider`, which matches by
 * substring so it also catches variants not in this exact list).
 */
export const KNOWN_ENV_KEYS: string[] = (() => {
  const keys = new Set<string>();
  for (const provider of PROVIDERS) {
    const suffixes = CATEGORY_SUFFIXES[provider.category];
    const primary = provider.keywords[0].replace(/_$/, "");
    for (const suffix of suffixes) {
      keys.add(`${primary}_${suffix}`);
    }
  }
  return Array.from(keys).sort();
})();

/**
 * Finds the most specific provider whose keyword appears in the given env
 * var name. Prefers the longest matching keyword so that, e.g., a var
 * containing both "AWS_" and "AWS_S3" style tokens resolves to the more
 * specific vendor rather than the generic one.
 */
export function findProvider(key: string): Provider | undefined {
  const upper = key.toUpperCase();
  let best: Provider | undefined;
  let bestLength = 0;
  for (const provider of PROVIDERS) {
    for (const keyword of provider.keywords) {
      if (keyword.length > bestLength && upper.includes(keyword)) {
        best = provider;
        bestLength = keyword.length;
      }
    }
  }
  return best;
}

export const PROVIDER_COUNT = PROVIDERS.length;
