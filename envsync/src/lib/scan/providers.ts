import type { VariableCategory } from "./types";

/**
 * A curated knowledge base of real SaaS/dev-tool companies and the env var
 * name fragments their SDKs/docs conventionally use. This drives both
 * variable classification (`classifyVariable`) and provider identification
 * (`findProvider`) without any ML/LLM involved — it's a static lookup table,
 * same spirit as the original hand-written RULES list, just at the scale a
 * real multi-tenant scanning product needs (hundreds of vendors, not ten).
 *
 * `keywords` are matched as case-insensitive substrings against the env var
 * name. Longer/more specific keywords are preferred when several providers
 * match the same key (see `findProvider`), so listing a distinctive brand
 * token (e.g. "SENDGRID") is safer than a generic word.
 */
export interface Provider {
  name: string;
  category: VariableCategory;
  keywords: string[];
}

